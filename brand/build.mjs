await page.screenshot({ path: resolve(ROOT, 'public/og-image.png') });
console.log('  public/og-image.png');

// ---------------------------------------------------------------------------
// PWA icons
//
// A home-screen icon has to be PNG: iOS ignores an SVG apple-touch-icon, and
// Android's maskable icons get cropped to a circle or squircle, so that one
// needs the mark inset inside the safe zone or the spiral loses its edges.
// ---------------------------------------------------------------------------

/**
 * @param {number} size
 * @param {boolean} maskable  inset the mark and bleed the background to the edge
 */
async function renderIcon(size, maskable, out) {
  // Android crops up to 20% from each edge of a maskable icon, so that one
  // sits well inside the safe zone.
  const inset = maskable ? 0.58 : 0.78;
  const markSize = Math.round(size * inset);

  const html = `<!doctype html><html><head><meta charset="utf-8"><style>
    *{margin:0;padding:0;box-sizing:border-box}
    html,body{width:${size}px;height:${size}px;overflow:hidden}
    /* Square on purpose: iOS rounds the apple-touch-icon itself and Android
       masks adaptive icons, so pre-rounding here would double up. */
    body{background:${PALETTE.ink};
      display:flex;align-items:center;justify-content:center}
  </style></head><body>
    <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="${markSize}" height="${markSize}">
      ${earwormMark({ id: 'i' + size + (maskable ? 'm' : '') })}
    </svg>
  </body></html>`;

  const p = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
  await p.setContent(html, { waitUntil: 'load' });
  await p.screenshot({ path: resolve(ROOT, out) });
  await p.close();
  console.log('  ' + out);
}

mkdirSync(resolve(ROOT, 'public/icons'), { recursive: true });
await renderIcon(192, false, 'public/icons/icon-192.png');
await renderIcon(512, false, 'public/icons/icon-512.png');
await renderIcon(512, true, 'public/icons/icon-maskable-512.png');
// iOS uses this one, and does not apply a mask, so it keeps the rounded tile.
await renderIcon(180, false, 'public/icons/apple-touch-icon.png');

await browser.close();
console.log('\nDone. Tagline: ' + TAGLINE);
